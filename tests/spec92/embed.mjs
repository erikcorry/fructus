#!/usr/bin/env node
// embed.mjs - compile input files into the image, for spec92.h's fopen
//
//   node tests/spec92/embed.mjs out.c name=path ...
//
// Writes out.c with each file as a const array and mio_files[], the table
// mio_fopen searches, ended by a null name.  `name' is what the program asks
// fopen for; `path' is where the file is on the host.  With no files the
// table is just its terminator.

import { readFileSync, writeFileSync } from 'node:fs';

const [out, ...specs] = process.argv.slice(2);
if (!out) {
  console.error('usage: node tests/spec92/embed.mjs out.c name=path ...');
  process.exit(1);
}
let c = '/* Generated by tests/spec92/embed.mjs; do not edit.  */\n\n'
      + '#define SPEC92_NO_RENAMES\n#include "spec92.h"\n\n';
const rows = [];
specs.forEach((spec, i) => {
  const eq = spec.indexOf('=');
  const name = spec.slice(0, eq), data = readFileSync(spec.slice(eq + 1));
  c += `static const unsigned char f${i}[${data.length || 1}] = {`;
  for (let k = 0; k < data.length; k++)
    c += (k % 16 ? ' ' : '\n  ') + data[k] + ',';
  c += '\n};\n\n';
  rows.push(`  { ${JSON.stringify(name)}, f${i}, ${data.length} },\n`);
});
c += 'const struct mio_file mio_files[] = {\n' + rows.join('') + '  { 0, 0, 0 }\n};\n';
writeFileSync(out, c);
