#!/usr/bin/env node
// =============================================================================
// gen-font5.mjs - the dense terminal's 5x8 font, from Tommy Thorn's Spleentt
// =============================================================================
//
//   node terminal/gen-font5.mjs [SpleenttMedium-8.bdf] > terminal/font5.cc
//
// The font defaults to ~/github/spleentt-5x8-font/SpleenttMedium-8.bdf
// (github.com/tommythorn/spleentt-5x8-font, BSD 2-clause, from Frederic
// Cambus's Spleen).  Every glyph is 5x8, BBX 5 8 0 0, the descender on the
// bottom row.
//
// THE FONT is 128 codes, ASCII's: 0x20-0x7e are Spleentt's, 0x7f is
// FALLBACK, an empty box, for what the font lacks, and 0x01-0x0f are box
// drawing, light, a code its arms: up 1, down 2, left 4, right 8.  Each arm
// runs from the cell's edge to the middle, column 2, line 3, as Spleentt's
// own 11 do; the four half lines ╴╵╶╷ it lacks are made the same way.
// 0x00 and 0x10-0x1f are blank.  One font row a line, 128 bytes each, so the
// line table's font_line for line L is 2 L.  A row's five pixels are its
// byte's low five bits, bit 0 leftmost, as the display's 5-pixel cells take
// them (docs/vga.md, "Mode word"); BDF has them in the top five, bit 7
// leftmost, so the rows are drawn that way and reversed on the way out.
//
// BOX is each of U+2500-U+257F's code, from box-arms.mjs: one weight, so
// heavy, double, mixed, dashed and rounded are the light with the same arms.
// The diagonals ╱ ╲ ╳ have none, 0, and terminal.cc makes them / \ X.
// =============================================================================

import { readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { ARMS, DASHES, MIXED } from './box-arms.mjs';

const file = process.argv[2] ?? `${homedir()}/github/spleentt-5x8-font/SpleenttMedium-8.bdf`;
const LINES = 8, CODES = 128, FALLBACK = 0x7f;

const glyphs = new Map();
for (const g of readFileSync(file, 'latin1').split('STARTCHAR').slice(1)) {
  const code = +g.match(/^ENCODING (-?\d+)/m)[1];
  const bbx = g.match(/^BBX (.*)/m)[1];
  if (bbx !== '5 8 0 0') throw new Error(`glyph ${code}: BBX ${bbx}, not 5 8 0 0`);
  glyphs.set(code, g.split('BITMAP\n')[1].split('\n').slice(0, LINES).map((h) => parseInt(h, 16)));
}

const font = Array.from({ length: CODES }, () => new Array(LINES).fill(0));
for (let c = 0x20; c < 0x7f; c++) {
  if (!glyphs.has(c)) throw new Error(`no glyph for ${c}`);
  font[c] = glyphs.get(c);
}
font[FALLBACK] = [0x00, 0xf0, 0x90, 0x90, 0x90, 0x90, 0xf0, 0x00];

const UP = 1, DOWN = 2, LEFT = 4, RIGHT = 8, MIDDLE = 3;
for (let code = 1; code < 16; code++) {
  font[code] = Array.from({ length: LINES }, (_, l) =>
    ((code & UP && l <= MIDDLE) || (code & DOWN && l >= MIDDLE) ? 0x20 : 0) |
    (l === MIDDLE ? (code & LEFT ? 0xe0 : 0) | (code & RIGHT ? 0x38 : 0) : 0));
}

const box = new Array(128).fill(null);
const code = ([up, down, left, right]) => (up && UP) | (down && DOWN) | (left && LEFT) | (right && RIGHT);
for (const [ch, arms] of [...Object.entries(ARMS), ...Object.entries(MIXED)]) box[ch.codePointAt(0) - 0x2500] = code(arms);
for (const [ch, [, vertical]] of Object.entries(DASHES)) box[ch.codePointAt(0) - 0x2500] = vertical ? UP | DOWN : LEFT | RIGHT;
for (const [ch, arms] of Object.entries({ '╭': DOWN | RIGHT, '╮': DOWN | LEFT, '╯': UP | LEFT, '╰': UP | RIGHT }))
  box[ch.codePointAt(0) - 0x2500] = arms;
for (const ch of '╱╲╳') box[ch.codePointAt(0) - 0x2500] = 0;
if (box.includes(null)) throw new Error(`no arms for U+${(0x2500 + box.indexOf(null)).toString(16)}`);
for (let i = 0; i < 128; i++) {
  const g = glyphs.get(0x2500 + i);
  if (g && box[i] && g.join() !== font[box[i]].join())
    throw new Error(`U+${(0x2500 + i).toString(16)} is not Spleentt's`);
}

const reversed = (b) => [...Array(8)].reduce((v, _, x) => v | ((b >> x) & 1) << (7 - x), 0);
let out = `// Generated by terminal/gen-font5.mjs from Spleentt 5x8; do not edit.
#include "font5.h"

namespace terminal {

__attribute__((section(".font"))) const uint8_t FONT[LINES * 128] = {
`;
for (let l = 0; l < LINES; l++) {
  out += `  /* line ${l} */\n`;
  for (let c = 0; c < CODES; c += 16)
    out += '  ' + font.slice(c, c + 16).map((g) => '0x' + reversed(g[l]).toString(16).padStart(2, '0')).join(', ') + ',\n';
}
out += '};\n\nconst uint8_t BOX[128] = {\n';
for (let i = 0; i < 128; i += 16) out += '  ' + box.slice(i, i + 16).join(', ') + ',\n';
out += '};\n\n}  // namespace terminal\n';
process.stdout.write(out);
