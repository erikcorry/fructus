#!/usr/bin/env node
// =============================================================================
// gen-lib1funcs.js - libgcc/lib1funcs.s, one section per routine
// =============================================================================
//
//   node tools/gen-lib1funcs.js > vendor/gcc/libgcc/config/fructus/lib1funcs.S
//
// libgcc/lib1funcs.s is written in the customasm dialect: one flat namespace,
// no .globl, and no directives at all.  That is what lets the suite assemble
// it with customasm, decode the bytes back through the disassembler, and
// compare gas against customasm byte for byte - none of which would survive
// ELF paperwork sprinkled through the source.
//
// What the GCC tree needs is those same bytes WITH the paperwork: every entry
// point exported, and each one in a section of its own so that --gc-sections
// can drop the routines a program does not call.  lib1funcs.s is one object
// today, so a program that multiplies two ints links the 32-bit helper, the
// 64-bit helper and the whole division library along with it - measured at
// 528 bytes for a program whose only use of any of it was one calloc.
//
// So the copy in the GCC tree is GENERATED rather than identical, and
// tests/run.sh checks it is not stale, the same way it checks fructus-isa.h.
//
// SPLITTING IS ONLY SAFE WHERE NOTHING FALLS THROUGH.  Separate sections may
// be laid out in any order, so a routine that ran off its end into the next
// one would break - and break silently, since the bytes would still assemble.
// Every boundary is therefore proved rather than assumed: the last instruction
// before an entry point must be a `ret' or a jump, and this exits non-zero
// naming the routine if it is not.
// =============================================================================

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './isa.js';

const SRC = 'libgcc/lib1funcs.s';

// A routine starts at column zero; anything beginning with `.' is a local
// label, which is scoped to the routine above it and stays with it.
const ENTRY = /^([A-Za-z_][A-Za-z0-9_]*):/;

// The ways control leaves a routine for good.  A conditional branch is not
// one of them: it can fall through, which is exactly what this is looking for.
const LEAVES = /^(ret|jmpr?|halt)\b/;

const lines = readFileSync(join(root, SRC), 'utf8').split('\n');

const out = [
  '/* GENERATED by tools/gen-lib1funcs.js from ' + SRC + ' - do not edit.',
  '',
  '   The bytes are that file, which the fructus suite assembles with both',
  '   customasm and gas and checks against its own disassembler.  What is',
  '   added here is ELF paperwork: each entry point exported, and each one in',
  '   a section of its own so that --gc-sections drops what a program does',
  '   not call.  Run `npm run gcc\' to regenerate.  */',
  '',
];

let last = null;		// the last instruction, wherever it was
let broken = 0;

for (const line of lines) {
  const entry = ENTRY.exec(line);
  if (entry) {
    const name = entry[1];
    if (last !== null && !LEAVES.test(last)) {
      console.error(`gen-lib1funcs: ${name} is reached by falling out of the `
                  + `routine above it, whose last instruction is \`${last}'.`);
      console.error('  Separate sections may be laid out in any order, so the '
                  + 'two must stay together:');
      console.error('  end that routine with a jump, or teach this generator '
                  + 'which boundaries to skip.');
      broken = 1;
    }
    out.push(`\t.section\t.text.${name},"ax"`);
    out.push(`\t.globl\t${name}`);
    last = null;
  }

  out.push(line);

  // Comments, blank lines and labels are not instructions; local labels do
  // not end a routine, so they leave the last instruction standing.
  const code = line.replace(/^\s+/, '');
  if (code !== '' && !code.startsWith(';') && !code.startsWith('.')
      && !ENTRY.test(line))
    last = code;
}

if (broken)
  process.exit(1);

process.stdout.write(out.join('\n'));
