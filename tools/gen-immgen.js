#!/usr/bin/env node
// =============================================================================
// gen-immgen.js - the immediate unit, generated from isa/fructus.toml
// =============================================================================
//
//   node tools/gen-immgen.js > rtl/immgen.sv
//
// The 16-bit immediate right-hand side for every instruction that has one:
// the ALU and shift groups, mov, the load and store displacements, and the
// two mask branches.  A block RAM of 256 words, addressed in the dispatch
// cycle by the opcode's column and byte 1's top five bits, read out in
// decode - and imm10, which is wiring, beside it.
//
// THE VALUE TABLES ARE READ FROM THE SPEC, not transcribed.  tests/rtl-check.mjs
// generates its vectors from the same TOML and runs them against the
// generated Verilog under iverilog, so a table edit that the ROM does not hold
// fails the suite rather than shipping.
// =============================================================================

import { loadSpec } from './isa.js';

const spec = loadSpec();
const t = spec.optype;
const hex16 = (v) => `16'h${(((v) >>> 0) & 0xffff).toString(16).padStart(4, '0')}`;
const sext = (v, w) => (v & (1 << (w - 1)) ? v - (1 << w) : v);

// imm3 and shift3 are one table: they differ at index 0 alone, -1 against 15,
// and the shifter masks its right-hand side to four bits.
for (let n = 0; n < 8; n++)
  if ((t.imm3.values[n] & 15) !== (t.shift3.values[n] & 15))
    throw new Error(`shift3[${n}] is not imm3[${n}] & 15`);

// The columns are the ROM's high address bits: every form reading one of
// these tables must sit in its column, or the ROM is read at the wrong row.
// condimm5 is read at +6, where nothing has an immediate - see the header.
const COLUMN = { imm5: [0], condimm5: [0], imm10: [1], imm3: [2, 3], shift3: [2, 3], immbit5: [4], immask5: [5] };
const opcodeOf = (form) => form.encoding.replace(/_/g, '').split(/\s+/)[0];
for (const insn of spec.insn)
  for (const form of insn.form ?? []) {
    const op = opcodeOf(form);
    const types = Object.values(form.fields ?? {}).map((f) => f.split(':')[1].replace(/\[.*$/, ''));
    for (const ty of types.filter((x) => x in COLUMN)) {
      const cols = [...Array(8).keys()].filter((v) =>
        [0, 1, 2].every((k) => !/[01]/.test(op[5 + k]) || Number(op[5 + k]) === ((v >> (2 - k)) & 1)));
      if (cols.some((c) => !COLUMN[ty].includes(c)))
        throw new Error(`${insn.mnemonic}/${form.name}: ${ty} at column +${cols.join('/+')}, but rtl/immgen.sv reads it at +${COLUMN[ty].join('/+')}`);
    }
  }

// The opcodes that read their five bits as condimm5, from the spec: forms
// with a condimm5 field, whose opcode byte is all fixed bits.
const CIMM_OPS = [];
for (const insn of spec.insn)
  for (const form of insn.form ?? []) {
    if (!Object.values(form.fields ?? {}).some((f) => /:condimm5$/.test(f))) continue;
    const op = opcodeOf(form);
    if (!/^[01]{8}$/.test(op))
      throw new Error(`${insn.mnemonic}/${form.name}: a condimm5 form whose opcode has a field, ${op}`);
    CIMM_OPS.push(parseInt(op, 2));
  }
if (!CIMM_OPS.length) throw new Error('no condimm5 form: the +6 rows would be unread');
const CIMM_COL = 6;

// --- the ROM: {column, byte1[7:3]} -----------------------------------------
// undefined is a row nothing reads, written x.
const CCON = t.condimm5.values.map((e) => e[1]);
const word = (col, f5) => {
  switch (col) {
    case 0: return sext(f5, 5);                                   // imm5
    case 1: return f5 >> 3;                                       // imm10's bits 1:0, byte1[7:6]
    case 2: case 3: return t.imm3.values[((f5 >> 3) << 1) | (col & 1)];  // imm3
    case 4: return t.immbit5.values[f5];                          // immbit5
    case 5: return t.immask5.values[f5];                          // immask5
    case CIMM_COL: return CCON[f5];                               // condimm5
    default: return undefined;                                    // +7 has none
  }
};
const init = [];
for (let a = 0; a < 256; a++) {
  const v = word(a >> 5, a & 31);
  const lit = v === undefined ? "16'hxxxx"
    : a >> 5 === 1 ? `16'b${'x'.repeat(14)}${v.toString(2).padStart(2, '0')}`   // imm10: two bits read
    : hex16(v);
  init.push(`        rom[8'h${a.toString(16).padStart(2, '0')}] = ${lit};`);
}
const cimmExpr = CIMM_OPS.map((o) => `op == 8'h${o.toString(16)}`).join(' | ');

process.stdout.write(`// =============================================================================
// immgen.sv - the immediate right-hand side
// =============================================================================
//
// GENERATED by tools/gen-immgen.js from isa/fructus.toml.  Do not edit; edit
// the spec and regenerate with \`npm run rtl\`.
//
// A BLOCK RAM, READ AS THE INSTRUCTION DISPATCHES.  Every immediate but one
// is a function of eight bits: the opcode's column, opcode[2:0], and byte 1's
// top five bits.  So it is one SB_RAM40_4K of 256 x 16, addressed by
// rtl/cpu.sv's dispatch bytes, whose output register is the decode stage's
// - its value is there in decode, beside d_op and d_b1, as a flop of decode's
// own would be.  The remaining immediate, imm10, is byte 2 above byte 1's
// top two bits, and only those two are in the address: the ROM gives them,
// and one LUT a bit chooses byte 2 and its sign for the fourteen above, from
// a flop set in the same cycle.
//
// THE COLUMN IS THE MODE.  Every instruction with an immediate puts it in
// the same column of the opcode map - the generator checks - so the column
// picks the table:
//
//      +0  imm5      signed -16..15, and the tied load displacement
//      +1  imm10     signed, spanning two bytes: its low two bits
//      +2  imm3      the small-constant table, index {byte1[7:6], opcode[0]}
//      +4  immbit5   32 single-bit masks
//      +5  immask5   32 field and stripe masks
//      +6  condimm5  the packed branch's, which is at +0
//      +7            nothing
//
// THE PACKED BRANCH IS READ AT +6.  \`br cond, ra, #imm5\` puts a condimm5
// index where every other +0 form has a signed imm5, so it needs rows of its
// own; +6 has no immediate - its forms take port B from the bytes - so its
// rows are free, and the branch's opcode, ${CIMM_OPS.map((o) => `0x${o.toString(16)}`).join(', ')}, is steered there.  What +6
// and +7 read otherwise is meaningless, as are bits 15:2 of +1's rows: x,
// which yosys makes 0, and tests/dontcare-check.mjs fills every way.
//
// THE ADDRESS IS \`op\`, THE MASKED OPCODE, so an interrupt's brk reads what
// brk's column gives, as d_op has it - not the preempted instruction's.  brk
// reads no immediate; it is so that the ROM is a function of decode's bytes.
//
// IT REPLACED COMBINATIONAL LOGIC over decode's bytes - one nibble shifter for
// both mask tables, a case for imm3 and for condimm5, a tree on the column -
// 92 LUT4s alone: tools/gen-immgen.js before this, in the history.  A table
// in a ROM needs none of the properties that shifter relied on, so the mask
// tables may hold anything.
//
// MEASURED, yosys + nextpnr-ice40 on the UP5K, 2026-10-24, against the logic
// the same day:
//
//                                   LUT4   cells   median MHz   best
//     core, logic                   2606    3071     29.95      30.95   32 seeds
//     core, this ROM                2560    3024     30.41      31.26
//     system + UART + USB, logic    4119    5144     28.73      29.96   16 seeds
//     system + UART + USB, ROM      4050    5076     28.72      29.74
//
// AT THE SAME abc TARGET THE TABLE IS 86 LUT4s, and the target is worth six.
// With imm10 wholly beside the ROM, rather than its low two bits in +1's
// rows, the core came out 2514 LUT4 but at abc's Del 5374 against 5096 -
// the &dch flip - and 29.41 MHz median; this, the same RAM, maps to 4949.
// abc's choice between the two is worth 45 LUT4s and half a MHz either way,
// so a change smaller than that is not measured by one synthesis.
// =============================================================================

module immgen (
    input  logic        clk,
    input  logic [7:0]  op,     // dispatch: the opcode, masked as rtl/cpu.sv's d_op takes it
    input  logic [7:0]  b1,     // dispatch: byte 1, as d_b1 takes it
    input  logic [23:0] insn,   // decode: the instruction, byte 0 low - imm10's bytes
    output logic [15:0] imm     // decode: the immediate
);

    logic [15:0] rom [0:255];
    initial begin
${init.join('\n')}
    end

    wire        cimm = ${cimmExpr};
    wire  [7:0] addr = {cimm ? 3'd${CIMM_COL} : op[2:0], b1[7:3]};
    logic [15:0] q;
    logic        i10;                               // decode's column is +1
    always_ff @(posedge clk) begin
        q   <= rom[addr];
        i10 <= op[2:0] == 3'd1;
    end

    // imm10 is byte 1's top two bits and all of byte 2: the ROM has the two.
    assign imm = {i10 ? {{6{insn[23]}}, insn[23:16]} : q[15:2], q[1:0]};

endmodule
`);
