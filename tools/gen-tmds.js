#!/usr/bin/env node
// =============================================================================
// gen-tmds.js - rtl/video/tmds_rom.sv: pixel bytes to three TMDS symbols
// =============================================================================
//
//   node tools/gen-tmds.js
//
// See the header it writes.  It stops, writing nothing, if a symbol is not
// balanced or if any two video symbols on a lane put a control code on the wire
// at any offset.
// =============================================================================

import { writeFileSync } from 'node:fs';

// Bit 9 on the left; bit 0 goes first.  [level] -> symbol.
const GREEN = ['0001010111', '1100011001', '0100110011', '1110000011', '1000110011', '0011100110', '1110101000'];
const RED   = ['0001010111', '1100010011', '0001110110', '0011011100', '1101000110', '1110101000'];
const BLUE  = ['0001010111', '1111000001', '1110000011', '1110010100', '1110101000'];
const IDLE = '1101010100';
// Addresses 4-7, {vs pulse, hs pulse}: blue carries the sync pins' levels, low
// in a pulse.
const SYNC = ['1010101011', '0101010100', '0010101011', '1101010100'];

const CONTROL = new Set(['1101010100', '0010101011', '0101010100', '1010101011'].map((s) => parseInt(s, 2)));
for (const [name, lane] of [['green', GREEN], ['red', RED], ['blue', BLUE]]) {
  const syms = lane.map((s) => parseInt(s, 2));
  for (const s of lane)
    if ([...s].filter((c) => c === '1').length !== 5) throw new Error(`${name} ${s} is not balanced`);
  const blank = name === 'blue' ? SYNC.map((s) => parseInt(s, 2)) : [parseInt(IDLE, 2)];
  const window = (a, b, k) => ((a >> k) | (b << (10 - k))) & 1023;
  const check = (as, bs, from) => {
    for (const a of as) for (const b of bs) for (let k = from; k < 10; k++)
      if (CONTROL.has(window(a, b, k))) throw new Error(`${name}: ${a} then ${b} makes a control code at ${k}`);
  };
  for (const s of syms) if (CONTROL.has(s)) throw new Error(`${name}: ${s} is a control code`);
  check(syms, syms, 1);
  check(syms, blank, 1);
  check(blank, syms, 1);
}

const word = (b, g, r) => `30'b${r}_${g}_${b}`;
const rows = [];
for (let a = 0; a < 256; a++) {
  const t = a >> 5, c = a & 31, low = c & 15;
  let w;
  if (a >= 4 && a < 8) w = word(SYNC[a - 4], IDLE, IDLE);
  else if (t === 0 || low === 15) w = word(BLUE[0], GREEN[0], RED[0]);
  else w = word(BLUE[low % 5], GREEN[t - 1], RED[Math.floor(low / 5) + 3 * (c >> 4)]);
  rows.push(`        rom[8'h${a.toString(16).padStart(2, '0')}] = ${w};`);
}

writeFileSync('rtl/video/tmds_rom.sv', `// =============================================================================
// tmds_rom.sv - pixel bytes to three TMDS symbols, in two block RAMs
// =============================================================================
//
// GENERATED by tools/gen-tmds.js.  Do not edit.
//
// EVERY SYMBOL IS BALANCED, 5 ones and 5 zeros, so there is no running disparity
// to keep: the display's 7 x 6 x 5 colours are few enough to pick each level's
// nearest balanced symbol.  A symbol has at most 5 transitions, as an encoder's
// do, which costs black (7, not 0) and white (249, not 255); the worst other
// level is 4.5 off.  No two of a lane's video symbols, in either order, nor
// video and blanking, put a control code on the wire at any offset.
//
// Addresses 4 - 7 are blanking, {vsync pulse, hsync pulse}: control codes with
// negative syncs.  A pixel byte reaches them only from a palette entry of 4 - 7,
// so software must not write those.  The rest of 0x00 - 0x1f, and the two codes
// whose low four bits are all 1, are black.
//
// {red, green, blue}, each with bit 0 first on the wire.
// =============================================================================

module tmds_rom (
    input  logic        clk,
    input  logic [7:0]  addr,
    output logic [29:0] word
);

    logic [29:0] rom [0:255];
    initial begin
${rows.join('\n')}
    end

    always_ff @(posedge clk) word <= rom[addr];

endmodule
`);
