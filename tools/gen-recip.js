#!/usr/bin/env node
// =============================================================================
// gen-recip.js - the reciprocal unit and its table
// =============================================================================
//
//   node tools/gen-recip.js > rtl/recip.sv
//
// recip's answer is Moller and Granlund's v for a 16-bit word: with the
// divisor d normalised, 0x8000 <= d <= 0xffff,
//
//     v = floor((beta^2 - 1) / d) - beta,      beta = 2^16
//
// the 2/1 reciprocal.  The 3/2 reciprocal of a 32-bit divisor is made from it
// in software, libgcc/lib1funcs.s: as hardware it was a third product and a
// correction on 36-bit numbers, 480 logic cells - see isa/fructus.toml.
//
// THE 2/1 RECIPROCAL: thirty-two thousand answers, each of which must be
// exact.  No approximation is exact by itself - for some d the quotient lies
// within 1/d of an integer - so the unit approximates from below and then
// corrects, with one product to find out by how much.
//
// THE APPROXIMATION IS A STRAIGHT LINE IN EACH OF 128 SLOTS, indexed by
// d[14:8], with lo = d[7:0] along it:
//
//     v0 = A[i] - (S[i] * lo >> 12)
//
// A is sixteen bits and S fourteen, so the pairs are 128 x 32 bits: one
// block RAM of 256 x 16, A in the low half and S in the high.  Each slot's S
// is the slope with the least spread of v - v0 across it, and its A the
// least that keeps v0 <= v everywhere, so v0 is below by 0 .. 3: 1/x bends
// by more than two units of v across 256 values of d, which no slope
// removes.  Of the 32768, 23991 are exact, 8163 one below, 607 two and 7
// three.  Twice the slots, 256, would leave 0 .. 1 - and take two RAMs.
//
// THE CORRECTION is the remainder beta^2 - 1 - (beta + v0) * d, which lies
// in [0, 4d), so v2 = v0 + (r >= d) + (r >= 2d) + (r >= 3d).  Its low 19 bits
// are enough, and of beta * d only d[2:0] reaches them - see rtl/recip.sv.
//
// THIS SCRIPT CHECKS ALL 32768 answers with the unit's own arithmetic before
// it writes anything.  tests/rtl-check.mjs runs rtl/recip.sv itself over
// every operand against tools/sim.js.
// =============================================================================

const B = 0x10000;
const K = 7;                          // index bits, below d's top bit
const SEG = 1 << (15 - K);            // d values in a slot: 256
const SH = 12;                        // S's fraction bits
const exact = (d) => Math.floor(0xffffffff / d) - B;

const A = [], S = [];
for (let i = 0; i < 1 << K; i++) {
  const d0 = 0x8000 + i * SEG;
  const ex = Array.from({ length: SEG }, (_, lo) => exact(d0 + lo));
  const s0 = Math.round(((ex[0] - ex[SEG - 1]) / (SEG - 1)) * (1 << SH));
  let best = null;
  for (let s = s0 - 200; s <= s0 + 200; s++) {
    const need = ex.map((e, lo) => e + Math.floor((s * lo) / (1 << SH)));
    const spread = Math.max(...need) - Math.min(...need);
    if (!best || spread < best.spread) best = { spread, s, a: Math.min(...need) };
  }
  if (best.spread > 3) throw new Error(`slot ${i}: spread ${best.spread}, and the correction covers 3`);
  if (best.s < 0 || best.s >= 1 << 14 || best.a < 0 || best.a >= B)
    throw new Error(`slot ${i}: A ${best.a} or S ${best.s} out of range`);
  A.push(best.a); S.push(best.s);
}

// Every d, as rtl/recip.sv computes it.
const hist = [0, 0, 0, 0];
for (let d = 0x8000; d < 0x10000; d++) {
  const i = (d >> 8) & 0x7f, lo = d & 0xff;
  const v0 = A[i] - Math.floor((S[i] * lo) / (1 << SH));
  const p = (v0 * d) % 0x80000;                         // the product's low 19 bits
  const r = (~(p + (d & 7) * B)) & 0x7ffff;
  const n = (r >= d ? 1 : 0) + (r >= 2 * d ? 1 : 0) + (r >= 3 * d ? 1 : 0);
  if (v0 + n !== exact(d)) throw new Error(`d = 0x${d.toString(16)}: ${v0 + n}, not ${exact(d)}`);
  hist[n]++;
}

const hex = (v, n) => v.toString(16).padStart(n, '0');
const rom = [...A, ...S].map((w, k) => `        rom[8'h${hex(k, 2)}] = 16'h${hex(w, 4)};`).join('\n');

process.stdout.write(`// =============================================================================
// recip.sv - recip's answer: Moller and Granlund's v, in four held cycles
// =============================================================================
//
// GENERATED by tools/gen-recip.js, which says how the table was made and why
// the corrections are what they are.  Do not edit.
//
// BESIDE THE ALU, AS THE SB_MAC16s ARE.  recip is the ALU's op 14 with an
// lsel of 111, which zeroes all three halves of rtl/alu.sv's product, and
// rtl/cpu.sv ORs this unit's answer into it: p, a flop of its own, zero but
// in recip's last cycle.  So op 14 is still an OR and no mux grows an arm.
//
// rtl/cpu.sv KEEPS IT A MODULE OF ITS OWN, (* keep_hierarchy *), so that abc
// maps the processor without it.  Flattened in, the unit touched nothing on
// decode's paths and still made them deeper: every critical path - memory,
// the register number, the register file's read, aq - eight cells where it
// had been seven, 28.08 MHz against 30.38.  With the hierarchy kept they
// were seven again.
//
// THE ANSWER ENDS AT A FLOP, NOT AT A DSP's PIN.  Loaded instead into mul's
// own output registers, through macu's D and C inputs, it ended the first
// correction's path at a pin whose place is fixed, two long wires from the
// logic: 24.8 ns of its 37.2 routing, 28.78 MHz.  At a flop the placer puts
// beside it, 30.60.
// The unit reads aq in the instruction's first ALU cycle and rtl/cpu.sv's
// e_cnt after that, and nothing else.
//
// THE CYCLES, by e_cnt - which counts the held cycles still to come:
//
//     4      aq is d.  The RAM reads S[i], i = d[14:8], and dq takes d, its
//            top bit set whatever it was.
//     3      The first SB_MAC16 multiplies S by lo = d[7:0].  The RAM reads
//            A[i].
//     2      v0 = A - (S * lo >> 12), into vq and, without a flop between,
//            into the second SB_MAC16, which multiplies it by d.
//     1      r = beta^2 - 1 - (beta + v0) * d, in its low 19 bits; v =
//            v0 + (r >= d) + (r >= 2d) + (r >= 3d), into p.
//     0      op 14 reads p, and rd is written.
//
// THE TABLE is one block RAM, A at 0 .. 127 and S at 128 .. 255, read twice:
// S first, since the product needs it, and A while the product is made.
//
// v0 TO THE SECOND PRODUCT IS ONE CYCLE: the first SB_MAC16's output
// register, a sixteen-bit subtract and the second's multiplier.  nextpnr-ice40
// cannot time through an SB_MAC16, so \`just speed\` does not see it; icetime
// does.  A flop on v0 would cost a fifth held cycle.
//
// THE REMAINDER'S LOW 19 BITS ARE ENOUGH: r < 4d < 2^18.  beta^2 is zero
// there, and beta * d is d[2:0] at bits 18:16, so r is ~(p2 + {d[2:0], 0}) -
// a three-bit add on top of the product's own bits.  The three compares are
// a thermometer, so the count is {ge2, ge1 ^ ge2 ^ ge3}.
//
// Corrections over all 32768: 0 for ${hist[0]}, 1 for ${hist[1]}, 2 for ${hist[2]}, 3 for ${hist[3]}.
// =============================================================================

module recip (
    input  logic        clk,
    input  logic [15:0] a,       // aq: d, the divisor, in the first ALU cycle
    input  logic        go,      // recip is in the ALU stage: op 14, lsel 111
    input  logic [2:0]  cnt,     // rtl/cpu.sv's e_cnt: held cycles still to come
    output logic [15:0] p        // v, in the last cycle; zero in every other
);

    logic [15:0] rom [0:255];
    initial begin
${rom}
    end

    wire first = go & cnt == 3'd4;
    logic [15:0] dq, vq, w;
    logic [17:0] d3q;                       // 3d
    wire  [7:0]  ra = first ? {1'b1, a[14:8]} : {1'b0, dq[14:8]};
    always_ff @(posedge clk) begin
        w    <= rom[ra];
        if (first) dq <= {1'b1, a[14:0]};   // the top bit taken as 1
        d3q  <= {2'b0, dq} + {1'b0, dq, 1'b0};
    end

    // THE TWO PRODUCTS, each registered at its SB_MAC16's output: S * lo on
    // the first, v0 * d on the second.
    wire [31:0] p1, p2;
    wire [15:0] v0 = w - {6'd0, p1[21:12]};
    always_ff @(posedge clk) vq <= v0;
    wire  [15:0] m1a = w;
    wire  [15:0] m1b = {8'd0, dq[7:0]};

\`ifdef SYNTHESIS
 \`define RECIP_MAC
\`endif
\`ifdef CPU_CELLS
 \`define RECIP_MAC
\`endif
\`ifdef RECIP_MAC
    // rtl/alu.sv's macu, with its OLOADs tied off: the product through the
    // output register's adder, plus C and D, which are zero.
    SB_MAC16 #(
        .A_REG(1'b0), .B_REG(1'b0), .C_REG(1'b0), .D_REG(1'b0),
        .TOP_8x8_MULT_REG(1'b0), .BOT_8x8_MULT_REG(1'b0),
        .PIPELINE_16x16_MULT_REG1(1'b0), .PIPELINE_16x16_MULT_REG2(1'b0),
        .TOPOUTPUT_SELECT(2'b01), .BOTOUTPUT_SELECT(2'b01),
        .TOPADDSUB_LOWERINPUT(2'b10), .TOPADDSUB_UPPERINPUT(1'b1), .TOPADDSUB_CARRYSELECT(2'b00),
        .BOTADDSUB_LOWERINPUT(2'b10), .BOTADDSUB_UPPERINPUT(1'b1), .BOTADDSUB_CARRYSELECT(2'b00),
        .MODE_8x8(1'b0), .A_SIGNED(1'b0), .B_SIGNED(1'b0)
    ) mac1 (
        .CLK(clk), .CE(1'b1), .A(m1a), .B(m1b), .C(16'd0), .D(16'd0),
        .AHOLD(1'b0), .BHOLD(1'b0), .CHOLD(1'b0), .DHOLD(1'b0),
        .IRSTTOP(1'b0), .IRSTBOT(1'b0), .ORSTTOP(1'b0), .ORSTBOT(1'b0),
        .OLOADTOP(1'b0), .OLOADBOT(1'b0), .ADDSUBTOP(1'b0), .ADDSUBBOT(1'b0),
        .OHOLDTOP(1'b0), .OHOLDBOT(1'b0), .CI(1'b0), .ACCUMCI(1'b0), .SIGNEXTIN(1'b0),
        .O(p1), .CO(), .ACCUMCO(), .SIGNEXTOUT()
    );
    SB_MAC16 #(
        .A_REG(1'b0), .B_REG(1'b0), .C_REG(1'b0), .D_REG(1'b0),
        .TOP_8x8_MULT_REG(1'b0), .BOT_8x8_MULT_REG(1'b0),
        .PIPELINE_16x16_MULT_REG1(1'b0), .PIPELINE_16x16_MULT_REG2(1'b0),
        .TOPOUTPUT_SELECT(2'b01), .BOTOUTPUT_SELECT(2'b01),
        .TOPADDSUB_LOWERINPUT(2'b10), .TOPADDSUB_UPPERINPUT(1'b1), .TOPADDSUB_CARRYSELECT(2'b00),
        .BOTADDSUB_LOWERINPUT(2'b10), .BOTADDSUB_UPPERINPUT(1'b1), .BOTADDSUB_CARRYSELECT(2'b00),
        .MODE_8x8(1'b0), .A_SIGNED(1'b0), .B_SIGNED(1'b0)
    ) mac2 (
        .CLK(clk), .CE(1'b1), .A(v0), .B(dq), .C(16'd0), .D(16'd0),
        .AHOLD(1'b0), .BHOLD(1'b0), .CHOLD(1'b0), .DHOLD(1'b0),
        .IRSTTOP(1'b0), .IRSTBOT(1'b0), .ORSTTOP(1'b0), .ORSTBOT(1'b0),
        .OLOADTOP(1'b0), .OLOADBOT(1'b0), .ADDSUBTOP(1'b0), .ADDSUBBOT(1'b0),
        .OHOLDTOP(1'b0), .OHOLDBOT(1'b0), .CI(1'b0), .ACCUMCI(1'b0), .SIGNEXTIN(1'b0),
        .O(p2), .CO(), .ACCUMCO(), .SIGNEXTOUT()
    );
\`else
    logic [31:0] q1, q2;
    always_ff @(posedge clk) begin
        q1 <= m1a * m1b;
        q2 <= v0 * dq;
    end
    assign p1 = q1, p2 = q2;
\`endif

    // THE CORRECTION: v2, the answer.
    // n2 is at most 3, so only the low two bits add; the high fourteen are
    // vq's or vq's plus one, and that increment is made beside the compares
    // rather than after them.  Added whole, behind them, the two carry chains
    // in a row were the critical path in five seeds of sixteen - from mac2's
    // output, whose clock to out nextpnr does not count.
    wire [18:0] r   = ~{p2[18:16] + dq[2:0], p2[15:0]};
    wire        ge1 = r >= {3'd0, dq};
    wire        ge2 = r >= {2'd0, dq, 1'b0};
    wire        ge3 = r >= {1'b0, d3q};
    wire [1:0]  n2  = {ge2, ge1 ^ ge2 ^ ge3};
    wire [13:0] hi1 = vq[15:2] + 14'd1;
    wire [2:0]  lo  = {1'b0, vq[1:0]} + {1'b0, n2};
    wire [15:0] v2  = {lo[2] ? hi1 : vq[15:2], lo[1:0]};

    // THE ANSWER INTO A FLOP OF ITS OWN, which rtl/cpu.sv ORs into the
    // product: zero but in recip's last cycle.  The gates are flops, set the
    // cycle before.
    logic gs;
    always_ff @(posedge clk) begin
        gs <= go & cnt == 3'd2;
        p  <= gs ? v2 : 16'd0;
    end

endmodule
`);
